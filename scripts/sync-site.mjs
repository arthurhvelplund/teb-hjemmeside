import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { navigation, parents, themes } from './site-layout/config.mjs';

const defaultSite = new URL('../site/', import.meta.url);
const source = new URL('./site-layout/', import.meta.url);
const escape = value => value.replace(/[&"<>]/g, character => ({'&':'&amp;','"':'&quot;','<':'&lt;','>':'&gt;'}[character]));
const stamp = value => createHash('sha256').update(value).digest('hex').slice(0, 12);
export async function syncSite({ check = false, directory = defaultSite } = {}) {
  const site = directory;
  const changed = [];
  const save = async (url, content) => {
    const old = await readFile(url, 'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; return ''; });
    if (old === content) return;
    changed.push(fileURLToPath(url));
    if (!check) await writeFile(url, content);
  };
  const registry = await Promise.all(themes.map(async theme => {
    const start = Date.parse(theme.start), end = Date.parse(theme.end);
    if (!Number.isFinite(start) || !Number.isFinite(end) || end <= start) throw Error('Invalid seasonal dates: ' + theme.id);
    return { id: theme.id, start, end, full: await readFile(new URL(theme.full, source), 'utf8'), secondary: await readFile(new URL(theme.secondary, source), 'utf8') };
  }));
  const controller = await readFile(new URL('seasonal-controller.js', source), 'utf8');
  const themeScript = '// Generated by scripts/sync-site.mjs. Edit scripts/site-layout/.\n(function () {\n"use strict";\nconst themes = ' + JSON.stringify(registry) + ';\n' + controller + '\n})();\n';
  await save(new URL('js/seasonal-theme.js', site), themeScript);
  const header = (await readFile(new URL('header.html', source), 'utf8')).trim();
  const footer = (await readFile(new URL('footer.html', source), 'utf8')).trim();
  const assets = new Map([['js/seasonal-theme.js', themeScript]]);
  async function asset(path) {
    if (!assets.has(path)) assets.set(path, await readFile(new URL(path, site), 'utf8'));
    return path + '?v=' + stamp(assets.get(path));
  }
  for (const filename of (await readdir(site)).filter(name => name.endsWith('.html')).sort()) {
    const url = new URL(filename, site);
    let html = await readFile(url, 'utf8');
    if (!/<header\b[^>]*class="site-header"/.test(html)) {
      if (/\bdata-portal-redirect=/.test(html)) continue;
      throw Error('Side mangler fælles header. Brug grundstrukturen i docs/SHARED_SITE_LAYOUT.md: ' + filename);
    }
    if (!/<footer\b[^>]*class="site-footer"/.test(html) || !/<main\b/.test(html)) throw Error('Fælles side mangler main eller footer: ' + filename);
    const active = parents[filename] || filename;
    const nav = '<nav class="nav" id="primary-nav" aria-label="Hovedmenu">\n' + navigation.map(([href, label]) => {
      const classes = [href === 'bliv-medlem.html' ? 'nav-cta' : '', href === active ? 'active' : ''].filter(Boolean).join(' ');
      return `      <a href="${escape(href)}"${classes ? ` class="${classes}"` : ''}${href === active ? ' aria-current="page"' : ''}>${escape(label)}</a>`;
    }).join('\n') + '\n    </nav>';
    html = html.replace(/<header\b[^>]*class="site-header"[^>]*>[\s\S]*?<\/header>/, header.replace('{{navigation}}', nav));
    html = html.replace(/<footer\b[^>]*class="site-footer"[^>]*>[\s\S]*?<\/footer>/, footer);
    html = html.replace(/<main\b([^>]*)>/, (tag, attributes) => {
      if (/class="/.test(attributes)) return '<main' + attributes.replace(/class="([^"]*)"/, (_, value) => `class="${[...new Set([...value.split(/\s+/), 'site-main'])].join(' ')}"`) + '>';
      return '<main' + attributes + ' class="site-main">';
    });
    html = html.replace(/<section\b([^>]*class=")([^"]*)("[^>]*)>/g, (tag, before, classes, after) => {
      if (!classes.split(/\s+/).some(value => value === 'hero' || value === 'thank-you')) return tag;
      return '<section' + before + [...new Set([...classes.split(/\s+/).filter(value => value !== 'fp-hero'), 'page-hero'])].join(' ') + after + '>';
    });
    html = html.replace(/\s*<script\b[^>]*src="js\/seasonal-theme\.js[^"<>]*"[^>]*><\/script>/g, '');
    if (!/href="css\/layout\.css/.test(html)) html = html.replace(/(<link\b[^>]*href="css\/style\.css[^"<>]*"[^>]*>)/, '$1\n<link rel="stylesheet" href="css/layout.css">');
    if (!/href="css\/seasonal-themes\.css/.test(html)) html = html.replace('</head>', '<link rel="stylesheet" href="css/seasonal-themes.css">\n</head>');
    html = html.replace('</head>', '<script src="js/seasonal-theme.js"></script>\n</head>');
    const references = [...html.matchAll(/(?:href|src)="((?:css|js)\/[^"?<>]+)(?:\?[^"<>]*)?"/g)];
    for (const match of references) html = html.replaceAll(match[0], match[0].slice(0, match[0].indexOf('="') + 2) + await asset(match[1]) + '"');
    await save(url, html);
  }
  if (check && changed.length) throw Error('Fælles layout eller assetversioner er forældede. Kør node scripts/sync-site.mjs.\n' + changed.join('\n'));
  return changed;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const changed = await syncSite({ check: process.argv.includes('--check') });
  console.log(process.argv.includes('--check') ? 'Fælles layout og assetversioner stemmer.' : `Opdaterede ${changed.length} fælles side-/temafiler.`);
}
